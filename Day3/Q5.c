//Convert temparature from celsius to fahrenheit
#include <stdio.h>

int main() {
    float celsius, fahrenheit;

    printf("Enter temparature in celsius: ");
    scanf("%f", &celsius);

    celsius = 9/5 * (32 - fahrenheit);

    printf("The temparature in fahrenheit is: %.2f\n", celsius);

    return 0;

}
